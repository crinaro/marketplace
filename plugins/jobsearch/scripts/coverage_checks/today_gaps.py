"""Today's gaps (design-dashboard-redesign §3.6, §12; dashboard-redesign E): the first list on the page holds at most
five references, and a row it references is open.

    ledger_predates_today(ledger)       -> [gap]           LEDGER PREDATES TODAY: a REGENERATE gap
    check_today(page, ledger, expected) -> (gaps, line)    TODAY OVER CAP, TODAY ROW FOLDED: ENGINE gaps

LEDGER PREDATES TODAY. A ledger with no `today` block was written by a renderer older than Today (the first hygiene
run after an upgrade reads the page the old version made). Nothing about it is wrong by construction: regenerating
clears it, so it is the one new gap `coordinator.ENGINE_GAPS` leaves out (§10.3).

TODAY OVER CAP (§3.2, §3.6 rules 1 and 3, decision D-1). Any of: more than `CAP` items; an item with no in-page
link (`href="#..."`), so a reader cannot reach what it names; a PRIMARY row (`data-rec`) inside Today, which would
make a record two primary rows' worth of the reader's attention (Today holds `data-ref` references only); a page
with no Today list at all, whose cap therefore cannot be held. `CAP` is this module's own constant, never
`dashboard.caps.TODAY_CAP`: a gate that read the renderer's cap would loosen with it (the plant "Today's cap set to
50" is exactly that).

TODAY ROW FOLDED (§3.6 rule 2). A single item's `data-ref` names a record whose primary row sits inside a closed
`<details>`: the reader follows the link and lands on nothing visible. Level 1 of each section holds every row Today
references (`caps.levels(..., pinned=...)`); this is the page-side proof of it.

Pure: no I/O; `expected` is accepted for the uniform signature and not read."""
from coverage_checks.walk import walk

CAP = 5                                 # design §3.2, D-1: "5 items. Never more."


def ledger_predates_today(ledger):
    """[gap] when the ledger has no `today` block (the module docstring), else []."""
    if isinstance(ledger, dict) and "today" in ledger:
        return []
    return ["LEDGER PREDATES TODAY -- views/dashboard_coverage.json has no `today` block: the page was generated by a "
            "renderer older than the Today list (an upgrade since). Regenerate the dashboard and re-check; nothing on "
            "the page is checked against a ledger that cannot describe it"]


def _is_link(href):
    return isinstance(href, str) and href.startswith("#") and len(href) > 1


def check_today(page, ledger, expected=None):
    """(gaps, line): TODAY OVER CAP and TODAY ROW FOLDED over `page` (the module docstring)."""
    w = walk(page)
    if w.today is None:
        return (["TODAY OVER CAP -- the page has no Today list (`<section class=\"today\">`), so its cap of %d cannot "
                 "be held; Today is always on the page, as items or its one sentence (design §3.5)" % CAP],
                "today: NO TODAY LIST")
    gaps = []
    items = w.today.items
    if len(items) > CAP:
        gaps.append("TODAY OVER CAP -- Today shows %d items; the cap is %d, and what does not fit is one \"Also "
                    "below\" line (design §3.2)" % (len(items), CAP))
    for attrs, hrefs in items:
        if not any(_is_link(h) for h in hrefs):
            gaps.append("TODAY OVER CAP -- the Today item %r carries no in-page link, so the reader cannot reach what "
                        "it names (design §3.6 rule 1)" % (attrs.get("data-ref") or attrs.get("data-kind") or "?"))
    primaries = [r.attrs["data-rec"] for r in w.rows if r.in_today and "data-rec" in r.attrs]
    for key in primaries:
        gaps.append("TODAY OVER CAP -- a primary row (data-rec=%r) sits inside Today; Today holds references only "
                    "(data-ref), so no record gains a second primary row (design §3.6 rule 1)" % key)
    folded_at = {r.attrs["data-rec"]: r.fold for r in w.rows if not r.in_today and "data-rec" in r.attrs}
    n_refs = 0
    for attrs, _hrefs in items:
        key = attrs.get("data-ref")
        if key is None:
            continue
        n_refs += 1
        fold = folded_at.get(key)
        if fold is not None:
            gaps.append("TODAY ROW FOLDED -- Today names %s, but its row is inside a closed fold (%r): a referenced "
                        "row is open, in level 1 of its section (design §3.6 rule 2)" % (key, w.folds[fold][1][:60]))
    return gaps, "today: %d item(s) of at most %d, %d reference(s), %d primary row(s) inside" % (
        len(items), CAP, n_refs, len(primaries))
